-- 上游模型降智检测：记录本次检测生成题（render）的单题超时（秒）。
--
-- 为什么要单独存这一列：生成题要吐一整份 HTML 文档，上游快慢能差 3~4 倍
--（生产实测同一道题在 codex 系路由要 354.9s，非 codex 分组只要 83~118s），
-- 因此单题超时做成可调、默认 15 分钟。不存这一列的话：
--   1) 历史记录里看不出「这一轮等的上限是多少」，同一个模型两次耗时差 4 倍时无法归因；
--   2) 判断 running 行是否已失效（进程重启残留）只能一律按最大超时算 ——
--      选了短超时的记录要白等一个多小时才会被标失败。
--
-- 默认 900 秒 = 15 分钟，即代码里的默认超时。本列落地之前的历史行会拿到这个默认值
--（它们当时用的是写死的 6 分钟上限）—— 不影响任何判定：该列只在行仍为 running 时
-- 参与失效判断，而历史行都已完结，剩下的差异只是展示。
ALTER TABLE model_audit_runs
    ADD COLUMN IF NOT EXISTS render_timeout_seconds INTEGER NOT NULL DEFAULT 900;
